"""Traces the GoAnime mark into the vector layers the hero's dragon animates.

Reads public/brand/goanime-mark.png and writes components/dragon-paths.ts:
one SVG path for the pale body and one for each crimson piece drawn over it
(the wing band, the crest, the jaw marking and the eye), on the PNG's
1024x1024 grid. Run it again whenever the mark changes:

    uv run scripts/trace-mark.py

potracer is pinned: it decides the paths. Without uv, any Python 3.9+ with
the four packages works:

    python3 -m venv /tmp/trace && /tmp/trace/bin/pip install pillow numpy scipy potracer==0.0.4
    /tmp/trace/bin/python scripts/trace-mark.py
"""

from pathlib import Path

import numpy as np
import potrace
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public/brand/goanime-mark.png"
TARGET = ROOT / "components/dragon-paths.ts"

pixels = np.array(Image.open(SOURCE).convert("RGBA"))
r, g, b, a = (pixels[..., i].astype(int) for i in range(4))
crimson = (a > 128) & (r > g + 60)
pale = (a > 128) & ~crimson

# The crimson pieces are separate shapes; name each one by where it sits.
labels, count = ndimage.label(crimson)
pieces = {}
for index in range(1, count + 1):
    ys, xs = np.where(labels == index)
    if len(xs) < 50:  # anti-aliasing specks
        continue
    pieces[index] = (len(xs), xs.min(), ys.min())


def find(test):
    return next(index for index, (size, x0, y0) in pieces.items() if test(size, x0, y0))


masks = {
    "wing": labels == find(lambda size, x0, y0: y0 < 40),  # reaches the top edge
    "mane": labels == find(lambda size, x0, y0: 140 < y0 < 170),  # the crest over the head
    "jaw": labels == find(lambda size, x0, y0: x0 < 130),  # reaches the snout
    "eye": labels == find(lambda size, x0, y0: size < 1000),  # the smallest
}
# The body with the eye's hole filled, so a closed eye shows skin, not a gap.
masks["body"] = pale | ndimage.binary_dilation(masks["eye"], iterations=4)


def trace(mask):
    # potrace takes dark pixels as the shape, hence the inversion.
    curves = potrace.Bitmap(~mask).trace(turdsize=30, alphamax=1.0, opticurve=True, opttolerance=0.2)
    out = []
    for curve in curves:
        p = curve.start_point
        out.append(f"M{p.x:.1f} {p.y:.1f}")
        for seg in curve.segments:
            if seg.is_corner:
                out.append(f"L{seg.c.x:.1f} {seg.c.y:.1f}L{seg.end_point.x:.1f} {seg.end_point.y:.1f}")
            else:
                out.append(
                    f"C{seg.c1.x:.1f} {seg.c1.y:.1f} {seg.c2.x:.1f} {seg.c2.y:.1f} "
                    f"{seg.end_point.x:.1f} {seg.end_point.y:.1f}"
                )
        out.append("Z")
    # Drop the ".0" of whole numbers.
    return "".join(out).replace(".0 ", " ").replace(".0C", "C").replace(".0L", "L").replace(".0Z", "Z")


lines = [
    "// The GoAnime mark as vector layers, traced with potrace from",
    "// public/brand/goanime-mark.png on its 1024x1024 grid: the pale body, and",
    "// the four crimson pieces drawn over it, each its own path so it can move",
    "// on its own. The body has the eye's hole filled, so a closed eye shows skin.",
    "// Generated by scripts/trace-mark.py; run it again if the mark changes.",
    "export const DRAGON_PATHS = {",
]
for key in ("body", "wing", "mane", "jaw", "eye"):
    lines.append(f'  {key}: "{trace(masks[key])}",')
lines.append("}")
TARGET.write_text("\n".join(lines) + "\n")
print(f"wrote {TARGET.relative_to(ROOT)}")
